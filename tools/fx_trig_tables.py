#!/usr/bin/env python3
"""Write src/fx/fx_tables.hpp: the integer tables and pi-derived constants of src/fx.

The world never calls libm. Everything it needs from sin, atan and pi is computed here once, in
double precision, rounded to integers and committed, so every compiler and instruction set reads
the same numbers. Run it again only to change a table; the output is checked in.

Units: a turn is 2^32 angle units (src/fx/angle.hpp); sines are Q30 (2^30 = 1.0); Fx is Q16.16.
"""
import math
from pathlib import Path

SEGMENTS = 1024  # table segments per quarter turn (sine) and per unit ratio (atan)
TURN = 1 << 32


def sine_q30():
    # sin over a quarter turn, SEGMENTS + 1 samples, Q30
    return [round(math.sin(i / SEGMENTS * math.pi / 2) * (1 << 30)) for i in range(SEGMENTS + 1)]


def atan_units():
    # atan(r) for r in [0, 1], SEGMENTS + 1 samples, in angle units (2^32 a turn)
    return [round(math.atan(i / SEGMENTS) / (2 * math.pi) * TURN) for i in range(SEGMENTS + 1)]


def rows(values, per_row=8):
    out = []
    for i in range(0, len(values), per_row):
        out.append("    " + ", ".join(str(v) for v in values[i:i + per_row]) + ",")
    return "\n".join(out)


def main():
    # radians (Q16.16 raw) to angle units: raw * 2^32 / (2 pi 2^16), as a multiplier over 2^16
    radians_to_units = round(TURN / (2 * math.pi * (1 << 16)) * (1 << 16))
    # degrees (Q16.16 raw) to angle units: raw * 2^32 / (360 2^16), as a multiplier over 2^22
    degrees_to_units = round(TURN / (360 * (1 << 16)) * (1 << 22))
    # angle units (signed) to radians (Q16.16 raw): units * 2 pi 2^16 / 2^32, a multiplier over 2^40
    units_to_radians = round(2 * math.pi * (1 << 16) / TURN * (1 << 40))

    text = f"""#pragma once
// GENERATED by tools/fx_trig_tables.py. Do not edit by hand.
#include <cstdint>

// clang-format off
inline constexpr int fx_table_segments = {SEGMENTS};

// sin over a quarter turn, {SEGMENTS + 1} samples, Q30
inline constexpr std::int32_t fx_sine_q30[{SEGMENTS + 1}] = {{
{rows(sine_q30())}
}};

// atan(r) for r = i / {SEGMENTS} in [0, 1], {SEGMENTS + 1} samples, in angle units (2^32 a turn)
inline constexpr std::int32_t fx_atan_units[{SEGMENTS + 1}] = {{
{rows(atan_units())}
}};

// raw Q16.16 radians times this, over 2^16, is angle units (2^32 / 2 pi)
inline constexpr std::int64_t fx_radians_to_units_q16 = {radians_to_units};
// raw Q16.16 degrees times this, over 2^22, is angle units (2^32 / 360)
inline constexpr std::int64_t fx_degrees_to_units_q22 = {degrees_to_units};
// signed angle units times this, over 2^40, is raw Q16.16 radians (2 pi / 2^32)
inline constexpr std::int64_t fx_units_to_radians_q40 = {units_to_radians};
// clang-format on
"""
    path = Path(__file__).resolve().parent.parent / "src" / "fx" / "fx_tables.hpp"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


if __name__ == "__main__":
    main()
